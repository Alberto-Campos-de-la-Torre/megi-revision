import { chromium } from '../../node_modules/playwright/index.mjs';
import { fileURLToPath } from 'node:url';
import { mkdirSync, writeFileSync } from 'node:fs';
const out=fileURLToPath(new URL('./',import.meta.url));
mkdirSync(out,{recursive:true});
const checks=[],errors=[],network=[];
const browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:1400,height:950},locale:'es-MX'});
page.on('pageerror', e=>errors.push(e.message));
page.on('response', r=>{if(r.status()>=400)network.push({status:r.status(),url:r.url().replace(/\?.*/, '')});});
const check=(id,ok,detail)=>{checks.push({id,passed:!!ok,...(detail===undefined?{}:{detail})});console.log((ok?'PASS ':'FAIL ')+id);};
const photo=(name)=>page.screenshot({path:out+'/'+name+'.png',fullPage:true});
const overflow=()=>page.evaluate(()=>({window:innerWidth,scroll:document.documentElement.scrollWidth}));
const chatText=()=>page.locator('article[data-role="assistant"] .agentkit-message-content').last().innerText();
try{
 await page.goto('http://127.0.0.1:8091/revision',{waitUntil:'networkidle'});
 const dev=page.getByRole('button',{name:/local dev|desarrollador local/i});
 if(await dev.count()){await dev.first().click();await page.waitForURL(/revision|home/);await page.goto('http://127.0.0.1:8091/revision',{waitUntil:'networkidle'});}
 await page.getByRole('link',{name:/Luis Modelo Simulado/}).waitFor({timeout:30000});
 check('cuatro-casos',await page.locator('main ul > li').count()===4);
 check('sin-enlace-inicio',await page.getByRole('link',{name:'Inicio',exact:true}).count()===0);
 const grid=await page.locator('main ul').evaluate(e=>getComputedStyle(e).gridTemplateColumns);
 check('dos-columnas-escritorio',grid.split(' ').length===2,grid);
 check('alergias-distinguidas',await page.getByText('Sin alergias conocidas (registrado)',{exact:true}).count()===1 && await page.getByText('Alergia: Penicilina',{exact:true}).count()===1);
 await photo('01-lista-desktop');
 await page.goto('http://127.0.0.1:8091/home',{waitUntil:'networkidle'});
 check('home-redirige-revision',new URL(page.url()).pathname==='/revision');
 await page.setViewportSize({width:390,height:844});
 let ov=await overflow();check('lista-movil-sin-overflow',ov.scroll<=ov.window,ov);
 await photo('02-lista-movil');
 await page.setViewportSize({width:1400,height:950});
 await page.goto('http://127.0.0.1:8091/chat',{waitUntil:'networkidle'});
 await page.getByRole('heading',{name:'Soy el agente de MEGI Revisión'}).waitFor({timeout:30000});
 check('chat-bienvenida-clinica',true);
 check('chat-tres-sugerencias',await page.locator('.bienvenida-agente__chip').count()===3);
 await photo('03-chat-desktop');
 await page.setViewportSize({width:390,height:844});
 ov=await overflow();check('chat-movil-sin-overflow',ov.scroll<=ov.window,ov);
 await photo('04-chat-movil');
 const editor=page.locator('[role="textbox"][contenteditable="true"]').last();
 await editor.scrollIntoViewIfNeeded();
 check('compositor-alcanzable-movil',await editor.isVisible());
 const chip=page.getByRole('button',{name:'¿Qué consultas tengo pendientes de revisión?',exact:true});
 await chip.scrollIntoViewIfNeeded();
 const chipRect=await chip.boundingBox();
 check('sugerencia-alcanzable-movil',chipRect && chipRect.y>=0 && chipRect.y+chipRect.height<=844,chipRect);
 await page.setViewportSize({width:1400,height:950});
 const phases=[];
 await page.exposeFunction('registrarFaseUx',d=>phases.push(d));
 await page.evaluate(()=>window.addEventListener('agentNative.chatRunning',e=>window.registrarFaseUx({running:e.detail?.isRunning,phase:e.detail?.phase})));
 await chip.click();
 const stop=page.getByRole('button',{name:/Stop generating|Stop response|Detener respuesta|Detener generación|Stop agent|Detener agente/i}).first();
 await stop.waitFor({state:'visible',timeout:20000});
 await photo('05-sugerencia-enviada');
 await stop.click();
 await stop.waitFor({state:'hidden',timeout:30000});
 check('sugerencia-envia-y-se-puede-cancelar',true);
 const send=page.getByRole('button',{name:/Send message|Enviar mensaje/}).last();
 await editor.fill('Lista las consultas pendientes con sus nombres. Solo consulta los datos; no crees ni cambies planes.');
 await send.click();
 await stop.waitFor({state:'visible',timeout:20000});
 check('envio-solapado-impedido',await send.count()===0 || await send.isDisabled());
 await stop.waitFor({state:'hidden',timeout:120000});
 await page.locator('article[data-role="assistant"] .agentkit-message-content').last().waitFor({timeout:10000});
 const respuesta=await chatText();
 check('nuevo-envio-tras-cancelar-responde',/Alba|Mateo|Rosa|Luis/.test(respuesta),respuesta.slice(0,700));
 await photo('06-respuesta-chat');
 await page.goto('http://127.0.0.1:8091/revision/demo-c4',{waitUntil:'networkidle'});
 await page.getByRole('button',{name:'Plan en blanco',exact:true}).click();
 await page.getByRole('button',{name:/Aprobar y exportar/}).waitFor();
 await page.getByLabel('Fármaco',{exact:true}).fill('Paracetamol');
 await page.getByLabel('Dosis',{exact:true}).fill('500 mg');
 await page.getByLabel('Frecuencia',{exact:true}).fill('cada 8 h');
 await page.getByLabel('Duración',{exact:true}).fill('3 días');
 await page.getByRole('button',{name:'Añadir',exact:true}).click();
 await page.getByText('Sin alertas detectadas',{exact:true}).first().waitFor();
 const line=page.locator('li[data-linea-id]',{hasText:'Paracetamol'}).first();
 await line.getByRole('button',{name:'Bloquear',exact:true}).click();
 await line.getByText('Bloqueada por el médico',{exact:true}).waitFor();
 check('bloqueo-conservado',await line.getByRole('button',{name:'Editar',exact:true}).count()===0);
 await page.setViewportSize({width:390,height:844});
 ov=await overflow();check('tablero-movil-sin-overflow',ov.scroll<=ov.window,ov);
 await photo('07-tablero-movil');
 await page.setViewportSize({width:1400,height:950});
 await page.getByRole('button',{name:/Aprobar y exportar/}).click();
 await page.getByText('Aprobar y exportar a MEGI',{exact:true}).waitFor();
 await page.getByRole('button',{name:/^Aprobar y exportar$/}).last().click();
 await page.getByText('Aprobado y exportado',{exact:true}).first().waitFor({timeout:30000});
 await page.getByRole('tab',{name:'Exportación',exact:true}).click();
 await page.getByText(/sha256:/).first().waitFor();
 check('aprobacion-exportacion-conservadas',await page.getByText(/MedicationRequest/).count()>0);
 await photo('08-exportacion');
 check('sin-errores-javascript',errors.length===0,errors);
}catch(e){check('excepcion',false,e.message);await photo('error').catch(()=>{});}
await browser.close();
writeFileSync(out+'/resultados.json',JSON.stringify({fecha:new Date().toISOString(),url:'http://127.0.0.1:8091',entorno:'Base temporal, MEGI mock; dos turnos de chat con modelo configurado',checks,errors,network},null,2)+'\n');
console.log(JSON.stringify({passed:checks.filter(c=>c.passed).length,failed:checks.filter(c=>!c.passed).length},null,2));
process.exitCode=checks.some(c=>!c.passed)?1:0;
